def create_sector_constituents_csv():
    """创建板块成分股CSV文件"""
    print("=" * 70)
    print("  创建A股板块成分股CSV文件（静态数据）")
    print("=" * 70)
    print()

    df = pd.DataFrame(SECTOR_DATA)

    # 添加更新时间
    df['更新时间'] = pd.Timestamp.now().strftime('%Y-%m-%d')

    # 保存为CSV
    output_file = OUTPUT_DIR / f"sector_constituents_static_{pd.Timestamp.now().strftime('%Y%m%d')}.csv"
    latest_file = OUTPUT_DIR / "sector_constituents_static_latest.csv"

    df.to_csv(output_file, index=False, encoding='utf-8-sig')
    df.to_csv(latest_file, index=False, encoding='utf-8-sig')

    print(f"✓ 文件已保存:")
    print(f"  - {output_file}")
    print(f"  - {latest_file} (最新版)")
    print()

    # 统计信息
    print(f"数据统计:")
    print(f"  - 板块数: {df['板块名称'].nunique()}")
    print(f"  - 股票数: {df['股票代码'].nunique()}")
    print(f"  - 总记录: {len(df)}")
    print()

    # 按板块统计
    sector_stats = df.groupby('板块名称').agg({
        '股票代码': 'count',
        '权重': 'mean'
    }).round(2)
    sector_stats.columns = ['股票数量', '平均权重']
    sector_stats = sector_stats.sort_values('股票数量', ascending=False)

    print("板块成分股统计:")
    print(sector_stats.to_string())
    print()

    # 数据来源说明
    print("数据来源:")
    print("  - 中证指数公司官网: https://www.csindex.com.cn/")
    print("  - 各指数成分股基于公开的指数编制方案")
    print()

    print("更新建议:")
    print("  - 更新频率: 每半年一次（6月、12月）")
    print("  - 更新方式: 访问中证指数官网下载最新成分股文件")
    print()

    return df

def main():
    """主函数"""
    print()
    create_sector_constituents_csv()

    print("=" * 70)
    print("  ✓ 创建完成!")
    print("=" * 70)
    print()

if __name__ == '__main__':
    main()
